/**
 * 가이드 본문. 표와 예시 숫자는 빌드할 때 계산기와 같은 공식으로 직접 계산합니다.
 * 금액 단위: 만원 (won()은 원 단위 표시)
 */
const kr = (man: number) => koreanAmount(Math.round(man)) || '0원';
const approxKr = (man: number) => '약 ' + koreanAmount(Math.floor(man / 100) * 100);
/** 총 이자(만원) */
const interestOf = (man: number, rate: number, years: number, grace = 0, method: Method = 'equal-payment') =>
  calculateLoan(man * 10000, rate, years, grace, method).reduce((s, r) => s + r.interest, 0) / 10000;
const dsrLimit = (income: number, rate: number, years: number, existing = 0) => principalFrom(Math.max(0, income * 0.4 - existing) / 12, rate, years);
/** 중개보수 상한(만원): 2021.10 개정 주택 매매 요율 */
export function brokerFee(price: number) {
  if (price < 5000) return Math.min(price * 0.006, 25);
  if (price < 20000) return Math.min(price * 0.005, 80);
  if (price < 90000) return price * 0.004;
  if (price < 120000) return price * 0.005;
  if (price < 150000) return price * 0.006;
  return price * 0.007;
}

